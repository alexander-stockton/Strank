function escapeValue(text) {
  return String(text).replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/\r/g, '');
}

function upsertKey(fileText, key, value) {
  const line = `${key}: ${escapeValue(value)}`;
  const re = new RegExp(`^${key.replace(/\./g, '\\.')}:.*$`, 'm');
  if (re.test(fileText)) return fileText.replace(re, line);
  // Insert before githubFab.aria when present, else append.
  if (/^githubFab\.aria:/m.test(fileText)) {
    return fileText.replace(/^githubFab\.aria:/m, `${line}\ngithubFab.aria:`);
  }
  return `${fileText.replace(/\s+$/, '')}\n${line}\n`;
}

function main() {
  for (const [tag, body] of Object.entries(BODIES)) {
    const file = path.join(LOCALE_ROOT, tag, 'ui-contributing.txt');
    if (!fs.existsSync(file)) {
      throw new Error(`missing ${file}`);
    }
    const next = upsertKey(fs.readFileSync(file, 'utf8'), 'contributing.aiUseBody', body);
    fs.writeFileSync(file, next.endsWith('\n') ? next : `${next}\n`, 'utf8');
    console.log(`updated ${tag}`);
  }
}

main();
